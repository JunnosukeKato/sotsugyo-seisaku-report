/**
 * 使い方（ヘルプ）の項目。学生用ツールの「？ 使い方」と、管理ページの「？ 使い方」で使う（mockups/v27 案A）。
 * 中身は、印刷用の手引き（docs/手引き_学生用.html・docs/手引き_教員用.html）から短くしたもの。
 * 1つの項目は、ひとこと（lead）＋手順2〜3つ（steps）まで。うまくいかないときなどは items に1〜2行で書く。
 * 画面の写真（shot）は public/help/ に置く（scripts/make-help-images.mjs で、本物のツールを撮って作る）。
 * 動画（video）は、あとで作ったものだけ入れる（入れた項目にだけ、再生の部品を出す）
 */

/** 端末ごとの手順（PDF の保存のしかたなど） */
export interface HelpDevice {
  id: 'pc' | 'mac' | 'iphone' | 'android'
  /** 切り替えのボタンの名前 */
  label: string
  lines: string[]
}

export interface HelpTopic {
  id: string
  /** 一覧で、この見出しの下にまとめる */
  group: string
  title: string
  /** ひとこと（1文） */
  lead?: string
  /** 手順（3つまで） */
  steps?: string[]
  /** 端末ごとの手順 */
  devices?: HelpDevice[]
  /** 補足（h：小見出し、t：文）。小見出しが「〜とき」で終わるものは、うまくいかないときの印（黄土色）で出す */
  items?: { h: string; t: string }[]
  /** 画面の写真（file：public/help/ のファイル名） */
  shot?: { file: string; caption: string }
  /** 動画（音なし・字幕つき。src：ファイルの場所、seconds：長さ） */
  video?: { src: string; seconds: number }
  /** 関係する項目の id */
  related?: string[]
  /** 文に出てこないが、よく使われる言い方（言葉で探すときだけ使う。空白で区切る） */
  words?: string
  /** 押すと何かをするボタン（tour：指差し確認をもう一度見る） */
  action?: { kind: 'tour'; label: string }
}

